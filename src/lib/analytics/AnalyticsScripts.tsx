import Script from "next/script";

type Props = { ga4Id: string | null; fbPixelId: string | null };

// Ids come from Admin → Settings; only safe characters reach the inline scripts.
const safe = (id: string | null) => (id && /^[A-Za-z0-9-]+$/.test(id) ? id : null);

/** GA4 + Meta Pixel base code. Renders nothing when neither id is configured. */
export function AnalyticsScripts({ ga4Id, fbPixelId }: Props) {
  const ga = safe(ga4Id);
  const pixel = safe(fbPixelId);

  return (
    <>
      {ga ? (
        <>
          <Script
            src={`https://www.googletagmanager.com/gtag/js?id=${ga}`}
            strategy="afterInteractive"
          />
          <Script id="ga4-init" strategy="afterInteractive">
            {`window.dataLayer=window.dataLayer||[];function gtag(){dataLayer.push(arguments);}window.gtag=gtag;gtag('js',new Date());gtag('config','${ga}');`}
          </Script>
        </>
      ) : null}
      {pixel ? (
        <Script id="meta-pixel" strategy="afterInteractive">
          {`!function(f,b,e,v,n,t,s){if(f.fbq)return;n=f.fbq=function(){n.callMethod?n.callMethod.apply(n,arguments):n.queue.push(arguments)};if(!f._fbq)f._fbq=n;n.push=n;n.loaded=!0;n.version='2.0';n.queue=[];t=b.createElement(e);t.async=!0;t.src=v;s=b.getElementsByTagName(e)[0];s.parentNode.insertBefore(t,s)}(window,document,'script','https://connect.facebook.net/en_US/fbevents.js');fbq('init','${pixel}');fbq('track','PageView');`}
        </Script>
      ) : null}
    </>
  );
}
